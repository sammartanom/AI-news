// Ask: a generated orientation for a search, built from the matching resources and citing them.
// Shown above search results on the browse page when answers are enabled.
import { h, fill } from './dom.js';
import { api } from './api.js';
import { openResource } from './dialog.js';

export function askButton(slot, getQ) {
  const btn = h('button', { type: 'button', id: 'ask', class: 'link' }, 'Ask');
  btn.addEventListener('click', async () => {
    btn.disabled = true;
    fill(slot, h('p', { class: 'status', role: 'status' }, 'Reading matching resources'));
    try {
      const d = await api.post('/api/ask', { q: getQ(), audience: 'Everyone' });
      fill(slot, renderAnswer(d));
    } catch (e) {
      fill(slot, h('p', { class: 'error', role: 'alert' }, e.status === 429 ? 'Too many questions. Try again in a minute.' : 'An orientation could not be generated. The results below are unaffected.'));
    }
    btn.disabled = false;
  });
  return btn;
}

function renderAnswer(d) {
  if (d.status === 'no_results') return h('p', { class: 'empty' }, d.message);
  if (d.status !== 'ok') return h('p', { class: 'error', role: 'status' }, d.message);
  const index = new Map(d.sources.map((s, i) => [s.id, i + 1]));
  const cites = (ids) => h('span', { class: 'cite' }, ids.map((id) => {
    const b = h('button', { type: 'button', 'aria-label': `Source ${index.get(id)}: ${d.sources.find((s) => s.id === id)?.title}` }, `[${index.get(id)}]`);
    b.addEventListener('click', () => openResource(id));
    return b;
  }));
  const item = (c) => h('li', {}, c.text, ' ', cites(c.sources));
  const start = d.start_with.map((id) => d.sources.find((s) => s.id === id)).filter(Boolean);
  return h('section', { class: 'answer', 'aria-labelledby': 'answer-h' },
    h('h2', { id: 'answer-h' }, 'Orientation, generated from these resources'),
    h('p', {}, d.orientation),
    d.considerations.length ? [h('h3', {}, 'Things to consider'), h('ul', {}, d.considerations.map(item))] : null,
    d.uncertainty.length ? [h('h3', {}, d.evidence === 'limited' ? 'Limits of this orientation' : 'Uncertainty'), h('ul', {}, d.uncertainty.map(item))] : null,
    start.length ? [h('h3', {}, 'Start with'), h('ul', {}, start.map((s) => h('li', {}, h('button', { class: 'link', type: 'button', onclick: () => openResource(s.id) }, s.title), ` · ${s.publisher}`)))] : null,
    h('p', { class: 'fine' }, d.basis, d.evidence === 'limited' ? ' Evidence here for this question is limited.' : ''),
    h('p', { class: 'fine' }, 'Generated by an AI model from the resources listed in the results. Check the sources before relying on it.')
  );
}
