import test, { before, after } from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from './helpers.mjs';
import { startServer } from '../harness/server.mjs';

let server, browser;
before(async () => { delete process.env.DEV_USER_EMAIL; server = await startServer({ answers: true }); browser = await chromium.launch(); });
after(async () => { await browser.close(); await server.close(); });

async function page() {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  return { page: await context.newPage(), context };
}

test('Ask Signal: a generated orientation appears above the results with citations, and says what it is based on', async () => {
  const { page: p, context } = await page();
  await p.goto(server.url + '/grid?q=' + encodeURIComponent('What should I understand about AI and student writing?'), { waitUntil: 'networkidle' });
  await p.waitForSelector('.rows .row');
  await p.getByText(/Do not enter student or other confidential information/).waitFor();
  const before = await p.locator('.rows .row').count();
  await p.getByRole('button', { name: 'Ask', exact: true }).click();
  const answer = p.locator('.answer');
  await answer.waitFor();
  assert.match(await answer.locator('h2').innerText(), /generated from these resources/i);
  assert.match(await answer.innerText(), /articles themselves were not read/);
  assert.match(await answer.innerText(), /Generated by an AI model/);
  assert.match(await answer.innerText(), /Evidence here for this question is limited/);
  const cite = answer.locator('.cite button').first();
  assert.match(await cite.getAttribute('aria-label'), /^Source \d+: /);
  assert.equal(await p.locator('.rows .row').count(), before, 'results stay in place');
  await cite.click();
  await p.locator('dialog[open] h2').waitFor();
  await context.close();
});

test('Ask Signal: if generation fails the results are untouched and the message is plain', async () => {
  const { page: p, context } = await page();
  await p.route('**/api/ask', (route) => route.fulfill({ status: 500, contentType: 'application/json', body: '{"error":"Request failed"}' }));
  await p.goto(server.url + '/grid?q=privacy', { waitUntil: 'networkidle' });
  await p.waitForSelector('.rows .row');
  await p.getByRole('button', { name: 'Ask', exact: true }).click();
  await p.getByRole('alert').waitFor();
  assert.match(await p.getByRole('alert').innerText(), /could not be generated\. The results below are unaffected/);
  assert.ok((await p.locator('.rows .row').count()) > 0);
  await context.close();
});

test('Ask Signal: the button is absent when answers are not enabled', async () => {
  const off = await startServer({ answers: false });
  const context = await browser.newContext();
  const p = await context.newPage();
  await p.goto(off.url + '/grid?q=privacy', { waitUntil: 'networkidle' });
  await p.waitForSelector('.rows .row');
  assert.equal(await p.getByRole('button', { name: 'Ask', exact: true }).count(), 0);
  await context.close();
  await off.close();
});
